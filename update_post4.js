セキュリティは、ソフトウェアなどの「技術」だけで守るものではありません。「契約」という法的根拠でも守る必要があります。クライアントから提供された機密情報をどう取り扱い、いつ破棄するのかを明確にしておくことが重要です。

**【対策手順】**
新規案件を受注する際は、作業を開始する前に必ずNDA（秘密保持契約書）を締結しましょう。多くの場合クライアント側から提示されますが、フリーランス側でも「クラウドサイン」などの電子契約サービスを利用して、独自のNDAテンプレートを用意しておくと、「この人はしっかりしている」と非常にプロフェッショナルな印象を与えられます。

